/** Общий язык матричного проявления: хеш, процедурный глиф и маска фронта.
 *
 *  Чанк один на все сцены — и на модель, и на фон с дождём, — чтобы знак на
 *  футболке и знак в фоне были одной рукой нарисованы. Разъедутся они
 *  мгновенно, если каждый шейдер заведёт свою сетку.
 *
 *  Глифы считаются процедурно, а не берутся атласом текстур: картинки с
 *  катаканой не существует в бюджете первой загрузки, а эти стоят ноль байт.
 *  Цвета здесь нет вообще — он приходит юниформами uFg/uBg из токенов
 *  секции, и за это держится тест tokens.test.ts. */
export const glyphChunk = /* glsl */ `
  float hash21(vec2 p) {
    p = fract(p * vec2(123.34, 456.21));
    p += dot(p, p + 45.32);
    return fract(p.x * p.y);
  }

  /** Знак внутри ячейки: решётка 3x5, зажжённая по хешу. Это не катакана и
   *  не пытается ей быть — на размере одной ячейки читается именно ритм
   *  штрихов, а не рисунок символа. */
  float glyphCell(vec2 cellUv, float seed) {
    vec2 block = floor(cellUv * vec2(3.0, 5.0));
    float on = step(0.45, hash21(block + seed * 17.0));

    // Поля внутри ячейки: без них соседние знаки слипаются в сплошную заливку.
    vec2 m = abs(cellUv - 0.5);
    float inside = step(m.x, 0.40) * step(m.y, 0.44);

    return on * inside;
  }

  /** Две зоны прохода по нормированной высоте h.
   *  x — меш уже проявлен (ниже фронта), y — светящаяся полоса у самого фронта.
   *  Выше фронта возвращается ноль: там меша ещё нет. */
  vec2 revealMask(float h, float front, float band) {
    float body = step(h, front);
    float edge = smoothstep(front - band, front, h) * body;
    return vec2(body, edge);
  }
`
