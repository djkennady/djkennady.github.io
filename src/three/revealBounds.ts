/** Высота точки внутри габарита меша, 0 — низ, 1 — верх.
 *
 *  Фронт проявления ходит в этих долях, а не в единицах сцены. Поэтому один
 *  и тот же шейдер одинаково проходит и по футболке из Tripo с её
 *  собственным масштабом, и по полотну ткани, и по любой модели, которая
 *  встанет на их место позже: подставлять множители под каждый меш руками
 *  не нужно.
 *
 *  Вырожденный габарит (плоский или перевёрнутый) — не поломка, а штатный
 *  вход: вернуть ноль честнее, чем NaN, который расползётся по шейдеру и
 *  погасит меш целиком. */
export function normalizeHeight(y: number, minY: number, maxY: number): number {
  const span = maxY - minY
  if (span <= 0) return 0
  return Math.min(1, Math.max(0, (y - minY) / span))
}
