import type { TierSettings } from '../lib/deviceTier'

/** Длительность прохода. Секция, мимо которой скроллят, а не демо, которое
 *  смотрят целиком: длиннее — и конец эффекта никто не увидит. */
export const REVEAL_DURATION = 2.8

/** Ширина светящейся полосы у фронта, в долях высоты меша. */
export const REVEAL_BAND = 0.14

/** Плотность сетки знаков по вертикали. Едет за уровнем устройства: на
 *  среднем знаки крупнее, и фрагментный шейдер считает их меньше.
 *
 *  Числа маленькие намеренно. Мелкая сетка выглядит разумной в коде и
 *  разваливается на экране: знак размером в несколько пикселей перестаёт
 *  читаться как знак, и вся сцена превращается в ровный шум. */
export function revealDensity(settings: TierSettings): number {
  return settings.segments >= 128 ? 18 : 13
}
